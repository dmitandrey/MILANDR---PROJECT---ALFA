char* u8_to_str(uint8_t value, char* buffer)
{
    char temp[4];
    int i = 0, j = 0;

    // Handle zero explicitly
    if (value == 0) {
        buffer[0] = '0';
        buffer[1] = '\0';
        return buffer;
    }

    // Convert digits to characters in reverse order
    while (value > 0) {
        temp[i++] = (value % 10) + '0';
        value /= 10;
    }

    // Reverse the string
    for (j = 0; j < i; ++j) {
        buffer[j] = temp[i - j - 1];
    }
    buffer[i] = '\0';

    return buffer;
}



